"use client";

import { useCallback, useEffect, useMemo, useState } from "react";
import Link from "next/link";
import { ReactFlowProvider } from "@xyflow/react";
import {
  BookOpen,
  CircleHelp,
  Eye,
  FlaskConical,
  ListChecks,
  Loader2,
  MessageSquare,
  MessageSquareOff,
  MousePointerClick,
  Plus,
  Sparkles,
  Upload,
} from "lucide-react";
import { StoreProvider, useStore } from "@/lib/store";
import { useCurrentUser } from "@/lib/firebase/FirebaseProvider";
import { getDb } from "@/lib/firebase/client";
import { doc, writeBatch } from "firebase/firestore";
import type { Team, TreeNode } from "@/lib/types";
import { AppHeader } from "./AppHeader";
import { TeamContext } from "./teamContext";
import { findNode } from "@/lib/tree";
import { TreeCanvas } from "./TreeCanvas";
import { DetailPanel } from "./DetailPanel";
import { ProgressPanel } from "./ProgressPanel";
import { ChatPanel } from "./ChatPanel";
import { HelpModal, NodeEditorModal, UploadResultModal } from "./Modals";
import { PaperSearchModal } from "./PaperSearchModal";
import { DecomposeModal } from "./DecomposeModal";
import { TreeGenerationModal } from "./teams/TreeGenerationModal";
import { UIContext, type EditorRequest, type UIContextValue } from "./uiContext";

// The whole HypoTree screen: header, toolbar, tree, detail panel and chat.

/** One team's tree, live from Firestore. Viewers get a read-only workspace. */
export function HypoTreeApp({ team, treeId }: { team: Team; treeId: string }) {
  const { uid } = useCurrentUser();
  const role = team.roles[uid];
  return (
    <StoreProvider
      key={`${team.id}/${treeId}`}
      teamId={team.id}
      treeId={treeId}
      canEdit={role === "owner" || role === "editor"}
    >
      <ReactFlowProvider>
        <TeamContext.Provider value={{ team, uid }}>
          <Workspace team={team} treeId={treeId} />
        </TeamContext.Provider>
      </ReactFlowProvider>
    </StoreProvider>
  );
}

function Workspace({ team, treeId }: { team: Team; treeId: string }) {
  const { state, dispatch, canEdit } = useStore();
  const [chatOpen, setChatOpen] = useState(true);
  const [editor, setEditor] = useState<EditorRequest | null>(null);
  const [uploadFor, setUploadFor] = useState<string | null>(null);
  const [paperSearchFor, setPaperSearchFor] = useState<string | null>(null);
  const [decomposeFor, setDecomposeFor] = useState<string | null>(null);
  const [helpOpen, setHelpOpen] = useState(false);
  const [showAutoGenerate, setShowAutoGenerate] = useState(false);
  // The Progress panel stays open until you select a different box.
  const [progressAnchor, setProgressAnchor] = useState<string | null | undefined>(undefined);
  const progressOpen = progressAnchor !== undefined && progressAnchor === state.selectedId;
  const setProgressOpen = (open: boolean) =>
    setProgressAnchor(open ? state.selectedId : undefined);

  const selected = findNode(state.nodes, state.selectedId);

  const handleAutoGenerated = useCallback(
    async (nodes: TreeNode[]) => {
      try {
        const db = getDb();
        const treeRef = doc(db, "teams", team.id, "trees", treeId);
        const batch = writeBatch(db);
        nodes.forEach((node, order) => {
          batch.set(doc(treeRef, "nodes", node.id), { ...node, order });
        });
        batch.update(treeRef, { updatedAt: Date.now() });
        await batch.commit();
        setShowAutoGenerate(false);
      } catch (err) {
        console.error("Failed to save generated tree:", err);
        setShowAutoGenerate(false);
      }
    },
    [team.id, treeId],
  );

  const ui: UIContextValue = useMemo(
    () => ({
      chatOpen,
      setChatOpen,
      openEditor: setEditor,
      openUpload: setUploadFor,
      openPaperSearch: (id) => setPaperSearchFor(id || state.selectedId || "root"),
      openDecompose: (id) => setDecomposeFor(id),
    }),
    [chatOpen, state.selectedId],
  );

  // Esc closes the side panels and modals.
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (
        e.key === "Escape" &&
        !editor &&
        !uploadFor &&
        !helpOpen &&
        !paperSearchFor &&
        !decomposeFor
      )
        dispatch({ type: "select", id: null });
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [dispatch, editor, uploadFor, helpOpen, paperSearchFor, decomposeFor]);

  // "Add Sub-Hypothesis" goes under the selected idea, or under the main idea.
  const addParentId =
    selected && (selected.kind === "hypothesis" || selected.kind === "root") && !selected.folded
      ? selected.id
      : "root";

  const counts = state.nodes.reduce(
    (acc, n) => {
      if (n.folded) return acc;
      if (n.kind === "hypothesis") acc.ideas++;
      if (n.kind === "experiment") acc.experiments++;
      if (n.status === "supported") acc.supported++;
      if (n.status === "contradicted") acc.contradicted++;
      if (n.kind === "suggestion") acc.suggestions++;
      return acc;
    },
    { ideas: 0, experiments: 0, supported: 0, contradicted: 0, suggestions: 0 },
  );

  if (state.missing) {
    return (
      <div className="flex h-dvh flex-col">
        <AppHeader crumbs={[{ label: team.name, href: `/teams/${team.id}` }]} />
        <div className="flex flex-1 flex-col items-center justify-center gap-3 text-sm text-slate-500">
          This tree was deleted, or you no longer have access to it.
          <Link href={`/teams/${team.id}`} className="font-medium text-indigo-700 hover:underline">
            Back to {team.name}
          </Link>
        </div>
      </div>
    );
  }
  if (!state.hydrated) {
    return (
      <div className="flex h-dvh items-center justify-center text-slate-400">
        <Loader2 className="size-5 animate-spin" />
      </div>
    );
  }

  return (
    <UIContext.Provider value={ui}>
      <div className="flex h-dvh flex-col bg-white text-slate-900">
        <AppHeader
          crumbs={[
            { label: team.personal ? "Personal" : team.name, href: `/teams/${team.id}` },
            { label: state.title || "…" },
          ]}
        >
          {!canEdit && (
            <span className="flex items-center gap-1 rounded-full bg-amber-50 px-2.5 py-1 text-xs font-medium text-amber-700">
              <Eye className="size-3.5" /> View only
            </span>
          )}
          <button
            onClick={() => setHelpOpen(true)}
            className="rounded-full p-1 transition hover:bg-slate-100 hover:text-slate-900"
            title="How HypoTree works"
          >
            <CircleHelp className="size-5" />
          </button>
        </AppHeader>

        {/* Toolbar */}
        <div className="flex shrink-0 flex-wrap items-center gap-2 border-b border-slate-200 px-5 py-2.5">
          {canEdit && (
            <button
              onClick={() => setEditor({ mode: "add", parentId: addParentId, kind: "hypothesis" })}
              className="flex items-center gap-1.5 rounded-lg bg-slate-900 px-3 py-1.5 text-[13px] font-medium text-white shadow-sm transition hover:bg-slate-800"
            >
              <Plus className="size-3.5" /> Add Sub-Hypothesis
            </button>
          )}
          {canEdit && state.nodes.length <= 1 && (
            <button
              onClick={() => setShowAutoGenerate(true)}
              className="flex items-center gap-1.5 rounded-lg border border-purple-300 bg-purple-50 px-3 py-1.5 text-[13px] font-medium text-purple-700 shadow-sm transition hover:bg-purple-100"
            >
              <Sparkles className="size-3.5 text-purple-600" /> Generate Tree (Claude &amp; Semantic Scholar)
            </button>
          )}
          <button
            onClick={() => setChatOpen(!chatOpen)}
            className="flex items-center gap-1.5 rounded-lg bg-slate-900 px-3 py-1.5 text-[13px] font-medium text-white shadow-sm transition hover:bg-slate-800"
          >
            {chatOpen ? <MessageSquareOff className="size-3.5" /> : <MessageSquare className="size-3.5" />}
            {chatOpen ? "Hide Chat" : "Show Chat"}
          </button>
          <button
            onClick={() => setProgressOpen(!progressOpen)}
            className={`flex items-center gap-1.5 rounded-lg border px-3 py-1.5 text-[13px] font-medium shadow-sm transition ${
              progressOpen
                ? "border-emerald-300 bg-emerald-100 text-emerald-800"
                : "border-emerald-200 bg-emerald-50/70 text-emerald-700 hover:bg-emerald-100"
            }`}
          >
            <ListChecks className="size-3.5" /> Progress
          </button>
          {canEdit && (
            <button
              onClick={() => setPaperSearchFor(selected?.id || "root")}
              className="flex items-center gap-1.5 rounded-lg border border-indigo-200 bg-indigo-50/70 px-3 py-1.5 text-[13px] font-medium text-indigo-700 shadow-sm transition hover:bg-indigo-100"
            >
              <BookOpen className="size-3.5" /> Search Literature
            </button>
          )}
          {canEdit && selected && selected.kind !== "experiment" && !selected.folded && (
            <button
              onClick={() => setDecomposeFor(selected.id)}
              className="flex items-center gap-1.5 rounded-lg border border-purple-200 bg-purple-50/70 px-3 py-1.5 text-[13px] font-medium text-purple-700 shadow-sm transition hover:bg-purple-100"
            >
              <Sparkles className="size-3.5" /> Break Down (Claude)
            </button>
          )}
          {canEdit && selected?.kind === "experiment" && (
            <button
              onClick={() => setUploadFor(selected.id)}
              className="flex items-center gap-1.5 rounded-lg border border-rose-200 bg-rose-50 px-3 py-1.5 text-[13px] font-medium text-rose-700 transition hover:bg-rose-100"
            >
              <Upload className="size-3.5" /> Upload Result
            </button>
          )}

          <div className="ml-auto hidden items-center gap-4 text-[12px] text-slate-500 lg:flex">
            <Stat n={counts.ideas} label="ideas" />
            <Stat n={counts.experiments} label="experiments" />
            <Stat n={counts.supported} label="supported" dot="bg-emerald-500" />
            <Stat n={counts.contradicted} label="contradicted" dot="bg-rose-500" />
            {counts.suggestions > 0 && (
              <Stat n={counts.suggestions} label="awaiting approval" dot="bg-sky-500" />
            )}
          </div>
        </div>

        {/* Workspace */}
        <main className="flex min-h-0 flex-1">
          <div className="relative min-w-0 flex-1 bg-[#fafbfc]">
            <TreeCanvas />
            <Legend />
            {!selected && state.nodes.length <= 1 && canEdit ? (
              <div className="absolute left-1/2 top-4 z-10 flex -translate-x-1/2 items-center gap-3 rounded-full border border-purple-200 bg-white/95 px-4 py-1.5 text-[12.5px] text-purple-900 shadow-sm backdrop-blur">
                <Sparkles className="size-4 text-purple-600" />
                <span>Tree has only a root hypothesis.</span>
                <button
                  onClick={() => setShowAutoGenerate(true)}
                  className="rounded-full bg-purple-600 px-3 py-0.5 font-medium text-white shadow-xs transition hover:bg-purple-700"
                >
                  Generate full tree with AI
                </button>
              </div>
            ) : !selected ? (
              <div className="pointer-events-none absolute left-1/2 top-4 flex -translate-x-1/2 items-center gap-2 rounded-full border border-slate-200 bg-white/90 px-4 py-1.5 text-[12.5px] text-slate-500 shadow-sm backdrop-blur">
                <MousePointerClick className="size-3.5" />
                Click any box to see its details and talk to its AI assistant
              </div>
            ) : null}
          </div>
          {progressOpen ? (
            <ProgressPanel onClose={() => setProgressOpen(false)} />
          ) : (
            <>
              {selected && <DetailPanel key={`d-${selected.id}`} node={selected} />}
              {selected && chatOpen && <ChatPanel key={`c-${selected.id}`} node={selected} />}
            </>
          )}
        </main>
      </div>

      {editor && <NodeEditorModal request={editor} onClose={() => setEditor(null)} />}
      {uploadFor && <UploadResultModal experimentId={uploadFor} onClose={() => setUploadFor(null)} />}
      {paperSearchFor && (
        <PaperSearchModal nodeId={paperSearchFor} onClose={() => setPaperSearchFor(null)} />
      )}
      {decomposeFor && (
        <DecomposeModal nodeId={decomposeFor} onClose={() => setDecomposeFor(null)} />
      )}
      {helpOpen && <HelpModal onClose={() => setHelpOpen(false)} />}
      {showAutoGenerate && (
        <TreeGenerationModal
          hypothesisTitle={state.title || "Research Hypothesis"}
          isOpen={showAutoGenerate}
          onSuccess={handleAutoGenerated}
          onCancel={() => setShowAutoGenerate(false)}
        />
      )}
    </UIContext.Provider>
  );
}

function Stat({ n, label, dot }: { n: number; label: string; dot?: string }) {
  return (
    <span className="flex items-center gap-1.5">
      {dot && <span className={`size-1.5 rounded-full ${dot}`} />}
      <b className="font-semibold tabular-nums text-slate-800">{n}</b> {label}
    </span>
  );
}

function Legend() {
  return (
    <div className="absolute left-4 top-4 z-10 hidden space-y-1.5 rounded-xl border border-slate-200 bg-white/90 px-3.5 py-3 text-[11.5px] text-slate-600 shadow-sm backdrop-blur md:block">
      <p className="mb-1 text-[10px] font-semibold uppercase tracking-wider text-slate-400">Legend</p>
      <LegendRow swatch="border-[1.5px] border-indigo-400 bg-white">Idea</LegendRow>
      <LegendRow swatch="border-[1.5px] border-rose-400 bg-white">
        <span className="flex items-center gap-1">
          Experiment <FlaskConical className="size-3 text-rose-400" />
        </span>
      </LegendRow>
      <LegendRow swatch="border-[1.5px] border-dashed border-sky-400 bg-sky-50">AI suggestion</LegendRow>
      <LegendRow swatch="border border-dashed border-slate-300 bg-slate-50">Folded away</LegendRow>
      <div className="flex items-center gap-2 pt-1">
        <span className="flex w-5 flex-col gap-0.5">
          <span className="h-px bg-indigo-300" />
          <span className="h-[3px] bg-indigo-400" />
        </span>
        Thicker = more confident
      </div>
    </div>
  );
}

function LegendRow({ swatch, children }: { swatch: string; children: React.ReactNode }) {
  return (
    <div className="flex items-center gap-2">
      <span className={`h-3 w-5 rounded-[3px] ${swatch}`} />
      {children}
    </div>
  );
}
